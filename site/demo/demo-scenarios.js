// What the metrics under the chart say is read from the same candles.
const MONTH = (() => {
 const first = CANDLES[0], last = CANDLES[CANDLES.length - 1];
 const drops = CANDLES.map((c, k) => ({ k, change: (c.close - c.open) / c.open * 100 }));
 const worst = drops.reduce((a, b) => b.change < a.change ? b : a);
 const high = Math.max(...CANDLES.map(c => c.high));
 const volume = CANDLES.reduce((sum, c) => sum + c.volume, 0) / CANDLES.length;
 const money = n => n.toLocaleString('en-US');
 return {
  close: money(last.close),
  closeRu: money(last.close).replace(/,/g, ' '),
  change: `+${((last.close - first.open) / first.open * 100).toFixed(1)}%`,
  trend: CANDLES.filter((_, k) => k % 6 === 0 || k === CANDLES.length - 1).map(c => (c.close / 1000).toFixed(1)).join(', '),
  worst: `−${Math.abs(worst.change).toFixed(1)}%`,
  worstDay: worst.k + 1,
  volume: `${(volume / 1000).toFixed(1)}K`,
  fromHigh: `−${((high - last.close) / high * 100).toFixed(1)}%`,
  high: money(high),
  highRu: money(high).replace(/,/g, ' '),
 };
})();

// Ten weeks of training minutes: more on the days of the plan, rest on Sundays, a missed week in the middle.
const MINUTES = (() => {
 const random = seeded(3), out = [];
 for (let k = 0; k < 70; k++) {
  const weekday = (k + 1) % 7, missed = k >= 28 && k < 33;
  const planned = [0, 55, 25, 60, 35, 60, 75][weekday];
  const minutes = missed || !planned ? 0 : Math.max(0, Math.round(planned * (0.7 + random() * 0.6)));
  out.push(`  ${day('2026-08-03', k)} | ${minutes}`);
 }
 return out;
})();

