function seeded(seed) {
 return () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
 };
}
const day = (start, k) => new Date(Date.parse(start) + k * 864e5).toISOString().slice(0, 10);

// A month of daily candles that climbs with a dip in the middle.
const CANDLES = (() => {
 const random = seeded(7), out = [];
 let close = 112400;
 for (let k = 0; k < 30; k++) {
  const drift = k < 11 ? 260 : k < 17 ? -540 : 520;
  const open = close, next = Math.round(open + drift + (random() - 0.5) * 2600);
  const high = Math.round(Math.max(open, next) + random() * 1100), low = Math.round(Math.min(open, next) - random() * 1100);
  out.push({ date: day('2026-09-12', k), open, high, low, close: next, volume: Math.round(18000 + random() * 24000) });
  close = next;
 }
 return out;
})();
